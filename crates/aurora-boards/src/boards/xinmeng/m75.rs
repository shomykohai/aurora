const QUIRKS: Quirks = Quirks {
    // Block 49 runs into the Fn keymap page and erases it.
    macro_block_cap: 48,
    // u32::MAX will fault the device
    macro_empty_marker: 0,
    inter_transfer_delay_ms: 3,
    flash_program_delay_ms: 35,
};

